def random_name(taken: Collection[str] = (), *, attempts: int = 50) -> str:
    """A fresh ``adjective-noun`` name not in ``taken``. After ``attempts`` collisions
    (vanishingly unlikely), disambiguate with a short hex suffix so the result is
    still unique."""
    for _ in range(attempts):
        name = f"{secrets.choice(_ADJECTIVES)}-{secrets.choice(_NOUNS)}"
        if name not in taken:
            return name
    while True:
        name = f"{secrets.choice(_ADJECTIVES)}-{secrets.choice(_NOUNS)}-{secrets.token_hex(2)}"
        if name not in taken:
            return name
